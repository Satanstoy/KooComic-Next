package.path = "./koocomic.koplugin/?.lua;" .. package.path
local available, Coordinator = pcall(require, "koobone.resource_coordinator")
assert(available, "resource coordination is not implemented")
local coordinator = Coordinator:new()
local download = assert(coordinator:acquire("download"))
assert(coordinator:acquire("preprocess") == nil, "heavy work must be exclusive")
assert(coordinator:release({ owner = "download" }) == false, "forged tokens must not unlock resources")
assert(coordinator:release(download))
local processing = assert(coordinator:acquire("preprocess"))
assert(coordinator:release(download) == false, "a late callback must not release a new owner's lock")
assert(coordinator:owner() == "preprocess")
assert(coordinator:release(processing))
assert(coordinator:owner() == nil)
print("resource coordinator spec: OK")
